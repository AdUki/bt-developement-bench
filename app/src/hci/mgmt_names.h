inline const char* mgmt_name(const char* const* t, size_t n, unsigned i) { return i < n && t[i][0] != '<' ? t[i] : nullptr; }
inline const char* mgmt_op_name(uint16_t op) { return mgmt_name(kMgmtOps, sizeof kMgmtOps / sizeof *kMgmtOps, op); }
inline const char* mgmt_event_name(uint16_t ev) { return mgmt_name(kMgmtEvents, sizeof kMgmtEvents / sizeof *kMgmtEvents, ev); }
inline const char* mgmt_status_name(uint8_t s) { return mgmt_name(kMgmtStatus, sizeof kMgmtStatus / sizeof *kMgmtStatus, s); }

